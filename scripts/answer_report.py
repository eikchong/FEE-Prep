def main():
    qs = list(all_questions(STUDY))
    by = collections.Counter(qd["answer_source"] for _, _, qd in qs)
    out = ["# Tutorial answer check", "", "Generated by `scripts/answer_report.py`; numbers are recomputed in "
           "`tests/test_tutorial_answers.py`.", "",
           f"{len(qs)} questions: {by['official']} official answers, {by['mine']} your own solutions, "
           f"{by['claude']} worked by Claude, {by['none']} not provided yet.", "",
           "## Where the official answer looks wrong", "", "| Subject | Question | Issue |", "|---|---|---|"]
    out += [f"| {c} | {s} | {m} |" for c, s, m in MISMATCHES]
    out += ["", "## Worked by Claude — please review", "",
            "No official or own solution exists for these. ✓ = numbers recomputed in the tests; ? = depends on "
            "reading a figure or an assumption, check first.", "", "| Subject | Question | Doc p. | |", "|---|---|---|---|"]
    for doc, _, qd in qs:
        if qd["answer_source"] == "claude":
            out.append(f"| {STUDY[doc]['code']} | {to_plain(qd['set'])} | {doc.rsplit('/', 1)[-1]} p. "
                       f"{qd['source']['page']} | {'✓' if qd['checked'] else '?'} |")
    out += ["", "## Not provided yet", ""]
    none = [f"- {STUDY[d]['code']} · {to_plain(qd['set'])}" for d, _, qd in qs if qd["answer_source"] == "none"]
    out += none or ["(none)"]
    (ROOT / "reports" / "answer_check.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(qs)} questions, {by}")


if __name__ == "__main__":
    main()
