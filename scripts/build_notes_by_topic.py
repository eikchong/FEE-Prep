"""Build data/notes_by_topic.json (+ reports/notes_unplaced.md) from STUDY and data/lecture_outlines.json.

Run after changing any utils/study_notes*.py file or the outlines:  python scripts/build_notes_by_topic.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from utils.notes_index import OUT_PATH, build  # noqa: E402
from utils.study_notes import STUDY  # noqa: E402


def main() -> dict:
    outlines = json.loads((ROOT / "data/lecture_outlines.json").read_text(encoding="utf-8"))
    syllabus = json.loads((ROOT / "data/syllabus.json").read_text(encoding="utf-8"))
    idx = build(STUDY, outlines, syllabus)
    OUT_PATH.write_text(json.dumps(idx, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    rep = ROOT / "reports" / "notes_unplaced.md"
    rep.parent.mkdir(exist_ok=True)
    lines = ["# Notes sections not placed under a topic", "",
             "Generated by `scripts/build_notes_by_topic.py`.", "",
             "| Doc | Section | Pages | Reason |", "|---|---|---|---|"]
    lines += [f"| {e['doc']} | {e['title']} | {e['pages'][0]}–{e['pages'][1]} | {e['reason']} |"
              for e in idx["excluded"]]
    rep.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(idx['sections'])} sections placed, {len(idx['excluded'])} excluded → {OUT_PATH.name}")
    return idx


if __name__ == "__main__":
    main()
